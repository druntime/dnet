/// Derive macro  that can be used to automatically implement
/// [IntoTransferable]/[FromTransferable] traits.
///
/// - fields of [transferable objects](https://developer.mozilla.org/en-US/docs/Web/API/Web_Workers_API/Transferable_objects)
///   need to be marked with `#[transferable]` attribute.
/// - fields holding types implementing [IntoTransferable]/[FromTransferable] need to be marked `#[into_transferable]` attribute,
/// - other fields need to be serializable (with [serde]).
///
/// [IntoTransferable]/[FromTransferable] implementations generated by this macro use [wrapper::Context].
/// Generated [Transferable] implementation is similar to the one used in [Wrapper] -
/// similar, but not exact - [Wrapper] isn't being used, instead a special type-specific wrapper is generated
/// for every type decorated with this derive macro.
///
/// See `transferable` example in `examples` directory for example use.
pub use dnet_macros::IntoTransferable;

